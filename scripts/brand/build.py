# Forewit brand: outlines the wordmark (Familjen Grotesk 600, OFL) with the climbing i dot, then writes the SVG set
# and web/src/brandMark.ts. PNGs: node scripts/brand/png.mjs. Run: .venv/Scripts/python.exe scripts/brand/build.py
import json, os
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FONT = os.path.join(ROOT, 'web/node_modules/@fontsource/familjen-grotesk/files/familjen-grotesk-latin-600-normal.woff')
OUT = os.path.join(ROOT, 'brand')
INK, OFF, LIME, OLIVE, BG = '#0B1220', '#F2F4F5', '#BCF053', '#385805', '#04090C'

f = TTFont(FONT)
gs, cmap, hmtx = f.getGlyphSet(), f.getBestCmap(), f['hmtx']
XH = f['OS/2'].sxHeight
TRACK = -12  # -0.01em, like the site headings


def path(glyph, x):
    pen = SVGPathPen(gs)
    gs[glyph].draw(TransformPen(pen, (1, 0, 0, -1, x, 0)))
    return pen.getCommands()


def bounds(glyph):
    b = BoundsPen(gs); gs[glyph].draw(b); return b.bounds


# Letters: F o r e w, a dotless i, then t; the i dot becomes three rising steps.
letters, x = [], 0
for ch in 'Forew':
    g = cmap[ord(ch)]; letters.append(path(g, x)); x += hmtx[g][0] + TRACK
ix0, _, ix1, _ = bounds('dotlessi')
letters.append(path('dotlessi', x))
stem = ix1 - ix0
s, gap = round(stem * 0.82), round(stem * 0.22)
left, base = x + ix0 + (stem - s) / 2, XH + round(stem * 0.55)
cells = [(0, 0), (1, 0), (1, 1), (2, 1), (2, 2)]
steps = ''.join(f'M{left + c * (s + gap):.0f} {-(base + r * (s + gap) + s):.0f}h{s}v{s}h-{s}z' for c, r in cells)
x += hmtx['dotlessi'][0] + TRACK
tg = cmap[ord('t')]
# The t clears every step column lower than its own top; a higher column may overhang it.
for c in range(3):
    if base + min(r for cc, r in cells if cc == c) * (s + gap) < bounds(tg)[3] + gap:
        x = max(x, left + c * (s + gap) + s + gap - bounds(tg)[0])
letters.append(path(tg, x))
x += hmtx[tg][0]
top = -(base + 2 * (s + gap) + s)
VB = (0, top - 20, round(x), round(-top + 20 + 14))  # descender free word; small pad
word = ''.join(letters)


def svg(vb, body, title='Forewit'):
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{" ".join(map(str, vb))}" role="img" aria-label="{title}"><title>{title}</title>{body}</svg>\n'


def wordmark(text, accent, bg=None, pad=0):
    vb = (VB[0] - pad, VB[1] - pad, VB[2] + 2 * pad, VB[3] + 2 * pad)
    back = f'<rect x="{vb[0]}" y="{vb[1]}" width="{vb[2]}" height="{vb[3]}" rx="{pad * 0.6:.0f}" fill="{bg}"/>' if bg else ''
    return svg(vb, f'{back}<path fill="{text}" d="{word}"/><path fill="{accent}" d="{steps}"/>')


# Icon: the climbing i alone, centred in a rounded square.
i_only = path('dotlessi', 0)
i_steps = ''.join(f'M{ix0 + (stem - s) / 2 + c * (s + gap):.0f} {-(base + r * (s + gap) + s):.0f}h{s}v{s}h-{s}z' for c, r in cells)
gx0, gx1 = ix0, ix0 + (stem - s) / 2 + 2 * (s + gap) + s
gy0, gy1 = top, 0
side = round(max(gx1 - gx0, gy1 - gy0) * 1.7)
cx, cy = (gx0 + gx1) / 2, (gy0 + gy1) / 2


def icon(text, accent, bg, radius=0.22):
    vb = (round(cx - side / 2), round(cy - side / 2), side, side)
    return svg(vb, f'<rect x="{vb[0]}" y="{vb[1]}" width="{side}" height="{side}" rx="{side * radius:.0f}" fill="{bg}"/><path fill="{text}" d="{i_only}"/><path fill="{accent}" d="{i_steps}"/>')


os.makedirs(OUT, exist_ok=True)
files = {
    'forewit_wordmark_dark.svg': wordmark(OFF, LIME),
    'forewit_wordmark_light.svg': wordmark(INK, OLIVE),
    'forewit_wordmark_on_dark.svg': wordmark(OFF, LIME, BG, 160),
    'forewit_wordmark_on_light.svg': wordmark(INK, OLIVE, '#F4F7F9', 160),
    'forewit_icon_dark.svg': icon(OFF, LIME, BG),
    'forewit_icon_light.svg': icon(INK, OLIVE, '#FFFFFF'),
}
for n, s_ in files.items():
    open(os.path.join(OUT, n), 'w', encoding='utf8', newline='\n').write(s_)
pub = os.path.join(ROOT, 'web/public')
open(os.path.join(pub, 'favicon.svg'), 'w', encoding='utf8', newline='\n').write(files['forewit_icon_dark.svg'])
open(os.path.join(pub, 'logo.svg'), 'w', encoding='utf8', newline='\n').write(files['forewit_wordmark_on_dark.svg'])
json.dump({'viewBox': VB, 'word': word, 'steps': steps, 'icon': {'viewBox': [round(cx - side / 2), round(cy - side / 2), side, side], 'i': i_only, 'steps': i_steps}},
          open(os.path.join(OUT, 'mark.json'), 'w', encoding='utf8'), indent=0)
open(os.path.join(ROOT, 'web/src/brandMark.ts'), 'w', encoding='utf8', newline='\n').write(
    '// Generated by scripts/brand/build.py: the Forewit wordmark outlined from Familjen Grotesk 600 (OFL), i dot as rising steps.\n'
    f'export const WORD_VIEWBOX = {json.dumps(' '.join(map(str, VB)))};\nexport const WORD_PATH = {json.dumps(word)};\nexport const STEPS_PATH = {json.dumps(steps)};\n')
print('ok', VB, 'stem', stem, 'step', s, gap)
