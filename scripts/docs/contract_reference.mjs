// Generates the GitBook contract reference pages from the compiled ABI and NatSpec (contracts/out), never by hand.
// Run after `forge build` in contracts/: node scripts/docs/contract_reference.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const PAGES = [
  { name: 'ForecastLedger', file: 'gitbook/developers/forecast_ledger_reference.md', address: '0xd11e67ff70ACD42E01d79130f280162b00Bb09B6', src: 'contracts/src/ForecastLedger.sol' },
  { name: 'ForewitScores', file: 'gitbook/developers/forewit_scores_reference.md', address: '0xb668BCC3cC103538d5B8e8c3F18B6E36a7dB0Fdc', src: 'contracts/src/ForewitScores.sol' },
];
const REPO = 'https://github.com/owaisahmad870/forewit/blob/main/';

// house style: no hyphen or dash characters in prose (OpenZeppelin NatSpec uses them)
const clean = (t = '') => t
  .replace(/\{(\w+)\}/g, '`$1`')
  .replace(/\s+-\s+/g, '; ')
  .replace(/(\w)-(\w)/g, '$1 $2')
  .replace(/[–—]/g, ', ')
  .replace(/\s+/g, ' ')
  .replace(/:\s*;/g, ':')
  .trim();
const sig = (x) => `${x.name}(${x.inputs.map((i) => i.type).join(',')})`;
const params = (list, docs = {}) => list.map((p, i) => `  * \`${p.type}${p.name ? ' ' + p.name : ''}\`${docs[p.name || `_${i}`] ? ': ' + clean(docs[p.name || `_${i}`]) : ''}`).join('\n');

export function render({ name, address, src }, artifact) {
  const { abi } = artifact;
  const { userdoc = {}, devdoc = {} } = artifact.metadata.output;
  const out = [`---\ndescription: Every external function, event and error of ${name}, generated from the compiled ABI and NatSpec.\n---\n`,
    `# Contract reference: ${name}`, '',
    `Generated by [scripts/docs/contract_reference.mjs](${REPO}scripts/docs/contract_reference.mjs) from the compiled ABI and NatSpec of [${src}](${REPO}${src}). Do not edit by hand.`, '',
    `* Address on BNB Smart Chain (chain 56): [${address}](https://bscscan.com/address/${address}), verified on BscScan and Sourcify.`];
  if (userdoc.notice) out.push(`* ${clean(userdoc.notice)}`);
  const section = (title, kind) => {
    const items = abi.filter((x) => x.type === kind).sort((a, b) => a.name.localeCompare(b.name));
    if (!items.length) return;
    out.push('', `## ${title}`);
    for (const x of items) {
      const s = sig(x);
      const u = (userdoc[kind === 'function' ? 'methods' : kind === 'event' ? 'events' : 'errors'] || {})[s];
      const d = (devdoc[kind === 'function' ? 'methods' : kind === 'event' ? 'events' : 'errors'] || {})[s];
      const notice = Array.isArray(u) ? u[0]?.notice : u?.notice;
      const details = Array.isArray(d) ? d[0]?.details : d?.details;
      const pdocs = (Array.isArray(d) ? d[0]?.params : d?.params) || {};
      out.push('', `### \`${s}\``, '');
      if (kind === 'function') out.push(`* Kind: ${x.stateMutability}`);
      if (notice) out.push(`* ${clean(notice)}`);
      if (details) out.push(`* Details: ${clean(details)}`);
      if (x.inputs.length) out.push(kind === 'event' ? '* Fields:' : '* Inputs:', params(x.inputs.map((i) => ({ ...i, type: i.indexed ? `${i.type} indexed` : i.type })), pdocs));
      if (kind === 'function' && x.outputs.length) out.push('* Returns:', params(x.outputs, (Array.isArray(d) ? d[0]?.returns : d?.returns) || {}));
    }
  };
  section('Functions', 'function');
  section('Events', 'event');
  section('Errors', 'error');
  return out.join('\n') + '\n';
}

if (import.meta.filename === process.argv[1]) {
  for (const p of PAGES) {
    const artifact = JSON.parse(readFileSync(`contracts/out/${p.name}.sol/${p.name}.json`, 'utf8'));
    mkdirSync('gitbook/developers', { recursive: true });
    writeFileSync(p.file, render(p, artifact));
    console.log(`${p.file}: ${artifact.abi.filter((x) => x.type !== 'constructor').length} entries`);
  }
}
